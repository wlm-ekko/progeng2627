#include <iostream>

int main(){
    int n, i = 0;
    // i indicates how many times we have printed

    std::cin >> n;

    // if the condition in the brakets is met, then we enter the while loop and execute instructions inside until condition is no longer met

    while(i < n){

        std::cout << "hello" << std::endl;

        i = i + 1;
        // increase counter by 1
    }

}